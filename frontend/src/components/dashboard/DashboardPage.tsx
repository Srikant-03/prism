/**
 * DashboardPage — Root orchestrator for the Power BI-grade AI Dashboard Builder.
 *
 * Manages:
 * - Multi-page workspace (PageTabs, drillthrough, page management)
 * - Power BI field wells, format panel, and visual picker
 * - DAX measure studio modal
 * - Bookmarks and saved views drawer
 * - Selection and layer order pane
 * - AI Explain Point drawer
 * - Interactive cross-filtering across visuals
 * - Create-vs-Edit strict isolation (prompting appends by default, mutates only in explicit edit mode)
 * - Global filters and date range filtering
 */
import React, { useState, useCallback, useRef, useEffect } from 'react';
import { message, Modal, List, Button } from 'antd';
import type {
    Widget,
    ChartConfig,
    FilterCondition,
    InterpretResponse,
    DashboardPage as DashboardPageType,
    MeasureDefinition,
    Bookmark,
} from '../../types/dashboard';
import DashboardHeader from './DashboardHeader';
import GlobalFilterBar from './GlobalFilterBar';
import DashboardCanvas from './DashboardCanvas';
import PromptBar from './PromptBar';
import PresentMode from './PresentMode';
import PageTabs from './PageTabs';
import FieldWellPanel from './FieldWellPanel';
import FormatPanel from './FormatPanel';
import MeasureStudioModal from './MeasureStudioModal';
import BookmarksDrawer from './BookmarksDrawer';
import SelectionPane from './SelectionPane';
import ExplainPointDrawer from './ExplainPointDrawer';
import { fetchAuth, API_BASE } from '../../api/client';
import { useTheme } from '../../hooks/useTheme';

interface PromptEntry {
    prompt: string;
    timestamp: number;
    chartTypeBefore?: string;
    chartTypeAfter?: string;
    widgetId?: string;
}

interface DashboardState {
    id: string;
    title: string;
    description: string;
    fileId: string;
    pages: DashboardPageType[];
    globalFilters: FilterCondition[];
    measures: MeasureDefinition[];
    bookmarks: Bookmark[];
}

interface DashboardListItem {
    id: string;
    title: string;
    description?: string;
    widget_count?: number;
    updated_at?: number;
}

interface Props {
    fileId: string;
    columns?: string[];
}

const DEFAULT_PAGE_ID = 'page-1';

const DashboardPage: React.FC<Props> = ({ fileId, columns = [] }) => {
    const { isDark } = useTheme();

    const [state, setState] = useState<DashboardState>({
        id: crypto.randomUUID?.() || Math.random().toString(36).slice(2),
        title: 'Untitled Dashboard',
        description: '',
        fileId,
        pages: [
            {
                id: DEFAULT_PAGE_ID,
                title: 'Executive Summary',
                widgets: [],
            },
        ],
        globalFilters: [],
        measures: [],
        bookmarks: [],
    });

    const [activePageId, setActivePageId] = useState<string>(DEFAULT_PAGE_ID);

    // Cross-filtering state
    const [crossFilters, setCrossFilters] = useState<Record<string, any>>({});

    // Side panels & drawers
    const [activeSidePanel, setActiveSidePanel] = useState<'field_well' | 'format' | null>(null);
    const [measureStudioOpen, setMeasureStudioOpen] = useState(false);
    const [bookmarksDrawerOpen, setBookmarksDrawerOpen] = useState(false);
    const [selectionPaneOpen, setSelectionPaneOpen] = useState(false);

    // AI Explain Point drawer state
    const [explainDrawerOpen, setExplainDrawerOpen] = useState(false);
    const [explainContext, setExplainContext] = useState<{
        metric: string;
        dimension: string;
        priorPoint: string;
        currentPoint: string;
    }>({ metric: '', dimension: '', priorPoint: '', currentPoint: '' });

    // Active & editing widget selection
    const [selectedWidgetId, setSelectedWidgetId] = useState<string | null>(null);
    const [editingWidgetId, setEditingWidgetId] = useState<string | null>(null);

    // Prompt bar state
    const [promptLoading, setPromptLoading] = useState(false);
    const [promptHistory, setPromptHistory] = useState<PromptEntry[]>([]);
    const [suggestions, setSuggestions] = useState<string[]>([]);
    const [clarification, setClarification] = useState<string | undefined>();

    // Present & save states
    const [presenting, setPresenting] = useState(false);
    const [saving, setSaving] = useState(false);
    const canvasRef = useRef<HTMLDivElement>(null);

    // Auto generation ref
    const [isAutoGenerating, setIsAutoGenerating] = useState(false);
    const autoGeneratedRef = useRef(false);

    // Snapshots for Undo
    const [configSnapshots, setConfigSnapshots] = useState<DashboardPageType[][]>([]);

    // Saved dashboards modal
    const [dashboardList, setDashboardList] = useState<DashboardListItem[]>([]);
    const [loadModalOpen, setLoadModalOpen] = useState(false);

    // Get current active page
    const currentPage = state.pages.find((p) => p.id === activePageId) || state.pages[0] || {
        id: DEFAULT_PAGE_ID,
        title: 'Executive Summary',
        widgets: [],
    };

    const currentWidgets = currentPage.widgets;
    const selectedWidget = currentWidgets.find((w) => w.id === selectedWidgetId);

    // Stable ref for widgets
    const widgetsRef = useRef<Widget[]>(currentWidgets);
    useEffect(() => {
        widgetsRef.current = currentWidgets;
    }, [currentWidgets]);

    // ── Load Dashboard List ──
    const handleLoadDashboard = async () => {
        try {
            const resp = await fetchAuth(`${API_BASE}/api/dashboards`);
            if (resp.ok) {
                const data = await resp.json();
                setDashboardList(data.dashboards || []);
                setLoadModalOpen(true);
            }
        } catch {
            message.error('Failed to load dashboards');
        }
    };

    // ── Select and Load a Dashboard ──
    const handleSelectDashboard = useCallback(async (id: string) => {
        try {
            const resp = await fetchAuth(`${API_BASE}/api/dashboards/${id}`);
            if (resp.ok) {
                const data = await resp.json();
                const loadedPages: DashboardPageType[] = data.pages && data.pages.length > 0
                    ? data.pages
                    : [
                        {
                            id: DEFAULT_PAGE_ID,
                            title: 'Executive Summary',
                            widgets: data.widgets || [],
                        },
                    ];

                setState((prev) => ({
                    ...prev,
                    id: data.id,
                    title: data.title || 'Untitled Dashboard',
                    description: data.description || '',
                    pages: loadedPages,
                    globalFilters: data.global_filters || [],
                    measures: data.measures || [],
                    bookmarks: data.bookmarks || [],
                }));
                setActivePageId(loadedPages[0].id);
                setLoadModalOpen(false);
                message.success('Dashboard loaded!');
            }
        } catch {
            message.error('Failed to load dashboard');
        }
    }, []);

    useEffect(() => {
        const params = new URLSearchParams(window.location.search);
        const dashId = params.get('dashboard');
        if (dashId) handleSelectDashboard(dashId);
    }, [handleSelectDashboard]);

    // ── Auto-generate initial dashboard if fileId is set ──
    useEffect(() => {
        const params = new URLSearchParams(window.location.search);
        if (params.get('dashboard')) return;

        if (!autoGeneratedRef.current && fileId) {
            autoGeneratedRef.current = true;
            setIsAutoGenerating(true);

            fetchAuth(`${API_BASE}/api/dashboard/auto`, {
                method: 'POST',
                headers: { 'Content-Type': 'application/json' },
                body: JSON.stringify({ file_id: fileId }),
            })
                .then((res) => {
                    if (!res.ok) throw new Error('Auto-gen failed');
                    return res.json();
                })
                .then((data) => {
                    if (data.widgets && data.widgets.length > 0) {
                        const newWidgets: Widget[] = data.widgets.map((w: any, idx: number) => ({
                            id: crypto.randomUUID?.() || Math.random().toString(36).slice(2),
                            config: w.config,
                            data: w.data || [],
                            sql: w.sql,
                            source_prompt: 'Auto-generated dashboard based on dataset context',
                            prompt_history: ['Auto-generated'],
                            error: w.error,
                            layout: {
                                x: (idx * 6) % 12,
                                y: Math.floor(idx / 2) * 4,
                                w: 6,
                                h: 4,
                            },
                        }));

                        setState((prev) => ({
                            ...prev,
                            pages: prev.pages.map((p) =>
                                p.id === activePageId ? { ...p, widgets: newWidgets } : p
                            ),
                        }));
                        message.success('Dashboard auto-generated based on business context!');
                    }
                })
                .catch((err) => {
                    console.error('Auto generation failed', err);
                })
                .finally(() => {
                    setIsAutoGenerating(false);
                });
        }
    }, [fileId, activePageId]);

    // ── Re-query a widget with global + cross filters ──
    const reQueryWidget = useCallback(
        async (widget: Widget, filters: FilterCondition[], activeCrossFilters: Record<string, any> = {}) => {
            try {
                // Combine global filters with cross filters
                const combinedFilters: FilterCondition[] = [...filters];
                for (const [col, val] of Object.entries(activeCrossFilters)) {
                    combinedFilters.push({ column: col, operator: '=', value: val });
                }

                const resp = await fetchAuth(`${API_BASE}/api/dashboard/query`, {
                    method: 'POST',
                    headers: { 'Content-Type': 'application/json' },
                    body: JSON.stringify({
                        config: widget.config,
                        file_id: fileId,
                        global_filters: combinedFilters,
                    }),
                });
                if (resp.ok) {
                    const data = await resp.json();
                    return data.data || [];
                }
                return widget.data || [];
            } catch {
                return widget.data || [];
            }
        },
        [fileId]
    );

    // ── Fetch Suggestions ──
    const fetchSuggestions = useCallback(async (config: ChartConfig) => {
        try {
            const resp = await fetchAuth(`${API_BASE}/api/dashboard/suggest`, {
                method: 'POST',
                headers: { 'Content-Type': 'application/json' },
                body: JSON.stringify({ file_id: fileId, current_config: config }),
            });
            if (resp.ok) {
                const data = await resp.json();
                setSuggestions(data.suggestions || []);
            }
        } catch {
            setSuggestions([]);
        }
    }, [fileId]);

    // ── Handle Prompt Submission (Isolated Create vs Explicit Edit) ──
    const handlePromptSubmit = useCallback(
        async (prompt: string) => {
            setPromptLoading(true);
            setClarification(undefined);

            try {
                const editingWidget = editingWidgetId
                    ? currentWidgets.find((w) => w.id === editingWidgetId)
                    : undefined;

                const body: any = {
                    message: prompt,
                    file_id: fileId,
                    conversation_history: promptHistory.map((h) => h.prompt),
                    edit_mode: Boolean(editingWidget),
                };
                if (editingWidget) {
                    body.current_config = editingWidget.config;
                }

                const resp = await fetchAuth(`${API_BASE}/api/dashboard/interpret`, {
                    method: 'POST',
                    headers: { 'Content-Type': 'application/json' },
                    body: JSON.stringify(body),
                });
                if (!resp.ok) throw new Error('Interpretation failed');
                const result: InterpretResponse = await resp.json();

                if (result.clarification) {
                    setClarification(result.clarification.clarification);
                    setSuggestions(result.clarification.suggestions || []);
                    return;
                }

                if (!result.success && result.error && !result.config) {
                    message.error(result.error);
                    return;
                }

                if (result.config) {
                    if (!result.success && result.error) {
                        message.warning(`Chart created but query had issues: ${result.error}`);
                    }

                    let targetWidgetId: string | null = null;

                    setState((prev) => {
                        // Capture snapshot for undo
                        setConfigSnapshots((snaps) => [...snaps, prev.pages.map((p) => ({ ...p, widgets: p.widgets.map((w) => ({ ...w })) }))]);

                        const isExplicitEdit = Boolean(editingWidgetId && currentWidgets.some((w) => w.id === editingWidgetId));

                        const updatedPages = prev.pages.map((page) => {
                            if (page.id !== activePageId) return page;

                            if (isExplicitEdit) {
                                targetWidgetId = editingWidgetId;
                                return {
                                    ...page,
                                    widgets: page.widgets.map((w) =>
                                        w.id === editingWidgetId
                                            ? {
                                                ...w,
                                                config: result.config!,
                                                data: result.data || w.data,
                                                sql: result.sql || w.sql,
                                                source_prompt: prompt,
                                                prompt_history: [...w.prompt_history, prompt],
                                                error: !result.success && result.error ? result.error : undefined,
                                            }
                                            : w
                                    ),
                                };
                            } else {
                                const newId = crypto.randomUUID?.() || Math.random().toString(36).slice(2);
                                targetWidgetId = newId;
                                const newWidget: Widget = {
                                    id: newId,
                                    config: result.config!,
                                    source_prompt: prompt,
                                    prompt_history: [prompt],
                                    layout: {
                                        x: (page.widgets.length * 6) % 12,
                                        y: Math.floor(page.widgets.length / 2) * 4,
                                        w: 6,
                                        h: 4,
                                    },
                                    data: result.data || [],
                                    sql: result.sql || undefined,
                                    error: !result.success && result.error ? result.error : undefined,
                                };
                                return { ...page, widgets: [...page.widgets, newWidget] };
                            }
                        });

                        return { ...prev, pages: updatedPages };
                    });

                    // Clear edit mode after submission so subsequent prompts create new widgets
                    setEditingWidgetId(null);
                    if (targetWidgetId) {
                        setSelectedWidgetId(targetWidgetId);
                    }

                    setPromptHistory((prev) => [
                        ...prev,
                        {
                            prompt,
                            timestamp: Date.now(),
                            chartTypeBefore: editingWidget?.config.chart_type,
                            chartTypeAfter: result.config!.chart_type,
                            widgetId: targetWidgetId || undefined,
                        },
                    ]);

                    fetchSuggestions(result.config);
                }
            } catch (err: any) {
                message.error(err.message || 'Failed to interpret prompt');
            } finally {
                setPromptLoading(false);
            }
        },
        [fileId, editingWidgetId, currentWidgets, promptHistory, activePageId, fetchSuggestions]
    );

    // ── Re-query all widgets on active page ──
    const reQueryAllWidgets = useCallback(async (filters: FilterCondition[], cross: Record<string, any>) => {
        const updatedWidgets = await Promise.all(
            currentWidgets.map(async (w) => ({
                ...w,
                data: await reQueryWidget(w, filters, cross),
            }))
        );
        setState((prev) => ({
            ...prev,
            pages: prev.pages.map((p) =>
                p.id === activePageId ? { ...p, widgets: updatedWidgets } : p
            ),
        }));
    }, [currentWidgets, reQueryWidget, activePageId]);

    // ── Cross-Filter Click Handler ──
    const handleCrossFilter = useCallback(
        async (column: string, value: any) => {
            const updatedCrossFilters = { ...crossFilters };
            if (updatedCrossFilters[column] === value) {
                delete updatedCrossFilters[column];
            } else {
                updatedCrossFilters[column] = value;
            }
            setCrossFilters(updatedCrossFilters);
            await reQueryAllWidgets(state.globalFilters, updatedCrossFilters);
        },
        [crossFilters, reQueryAllWidgets, state.globalFilters]
    );

    const handleRemoveCrossFilter = (column: string) => {
        const nextCross = { ...crossFilters };
        delete nextCross[column];
        setCrossFilters(nextCross);
        reQueryAllWidgets(state.globalFilters, nextCross);
    };

    const handleClearAllCrossFilters = () => {
        setCrossFilters({});
        reQueryAllWidgets(state.globalFilters, {});
    };

    // ── Global Filters ──
    const handleGlobalFiltersChange = useCallback(
        async (filters: FilterCondition[]) => {
            setState((prev) => ({
                ...prev,
                globalFilters: filters,
            }));
            await reQueryAllWidgets(filters, crossFilters);
        },
        [crossFilters, reQueryAllWidgets]
    );

    // ── Drill-Down / Drill-Up ──
    const handleDrillDown = async (widgetId: string) => {
        const target = currentWidgets.find((w) => w.id === widgetId);
        if (!target || !target.config.hierarchy_levels) return;

        const currentLvl = target.config.active_drill_level ?? 0;
        if (currentLvl < target.config.hierarchy_levels.length - 1) {
            const nextLvl = currentLvl + 1;
            const nextAxis = target.config.hierarchy_levels[nextLvl];
            const updatedConfig: ChartConfig = {
                ...target.config,
                active_drill_level: nextLvl,
                x_axis: nextAxis,
            };
            const updatedData = await reQueryWidget({ ...target, config: updatedConfig }, state.globalFilters, crossFilters);
            setState((prev) => ({
                ...prev,
                pages: prev.pages.map((p) =>
                    p.id === activePageId
                        ? {
                            ...p,
                            widgets: p.widgets.map((w) =>
                                w.id === widgetId ? { ...w, config: updatedConfig, data: updatedData } : w
                            ),
                        }
                        : p
                ),
            }));
        }
    };

    const handleDrillUp = async (widgetId: string) => {
        const target = currentWidgets.find((w) => w.id === widgetId);
        if (!target || !target.config.hierarchy_levels) return;

        const currentLvl = target.config.active_drill_level ?? 0;
        if (currentLvl > 0) {
            const prevLvl = currentLvl - 1;
            const prevAxis = target.config.hierarchy_levels[prevLvl];
            const updatedConfig: ChartConfig = {
                ...target.config,
                active_drill_level: prevLvl,
                x_axis: prevAxis,
            };
            const updatedData = await reQueryWidget({ ...target, config: updatedConfig }, state.globalFilters, crossFilters);
            setState((prev) => ({
                ...prev,
                pages: prev.pages.map((p) =>
                    p.id === activePageId
                        ? {
                            ...p,
                            widgets: p.widgets.map((w) =>
                                w.id === widgetId ? { ...w, config: updatedConfig, data: updatedData } : w
                            ),
                        }
                        : p
                ),
            }));
        }
    };

    // ── Open AI Explain Point ──
    const handleExplainWidget = (widget: Widget) => {
        const metric = widget.config.metrics?.[0]?.column || widget.config.y_axis || widget.config.kpi_value_column || 'net_revenue';
        const dimension = widget.config.group_by || widget.config.x_axis || 'product_category';

        setExplainContext({
            metric,
            dimension,
            priorPoint: 'Prior Period',
            currentPoint: 'Current Period',
        });
        setExplainDrawerOpen(true);
    };

    // ── Update Widget Config (via FieldWell or FormatPanel) ──
    const handleUpdateWidgetConfig = async (newConfig: ChartConfig) => {
        if (!selectedWidgetId) return;

        const target = currentWidgets.find((w) => w.id === selectedWidgetId);
        if (!target) return;

        const updatedData = await reQueryWidget({ ...target, config: newConfig }, state.globalFilters, crossFilters);

        setState((prev) => ({
            ...prev,
            pages: prev.pages.map((p) =>
                p.id === activePageId
                    ? {
                        ...p,
                        widgets: p.widgets.map((w) =>
                            w.id === selectedWidgetId ? { ...w, config: newConfig, data: updatedData } : w
                        ),
                    }
                    : p
            ),
        }));
    };

    // ── Page Management ──
    const handleAddPage = () => {
        const newId = crypto.randomUUID?.() || Math.random().toString(36).slice(2);
        const newPage: DashboardPageType = {
            id: newId,
            title: `Page ${state.pages.length + 1}`,
            widgets: [],
        };
        setState((prev) => ({ ...prev, pages: [...prev.pages, newPage] }));
        setActivePageId(newId);
        setSelectedWidgetId(null);
    };

    const handleRenamePage = (id: string, newTitle: string) => {
        setState((prev) => ({
            ...prev,
            pages: prev.pages.map((p) => (p.id === id ? { ...p, title: newTitle } : p)),
        }));
    };

    const handleDeletePage = (id: string) => {
        if (state.pages.length <= 1) return;
        const remaining = state.pages.filter((p) => p.id !== id);
        setState((prev) => ({ ...prev, pages: remaining }));
        if (activePageId === id) {
            setActivePageId(remaining[0].id);
        }
    };

    const handleDuplicatePage = (id: string) => {
        const target = state.pages.find((p) => p.id === id);
        if (!target) return;
        const newId = crypto.randomUUID?.() || Math.random().toString(36).slice(2);
        const duplicated: DashboardPageType = {
            ...target,
            id: newId,
            title: `${target.title} (Copy)`,
            widgets: target.widgets.map((w) => ({
                ...w,
                id: crypto.randomUUID?.() || Math.random().toString(36).slice(2),
            })),
        };
        setState((prev) => ({ ...prev, pages: [...prev.pages, duplicated] }));
        setActivePageId(newId);
    };

    // ── Selection Pane Actions ──
    const handleToggleVisibility = (widgetId: string) => {
        setState((prev) => ({
            ...prev,
            pages: prev.pages.map((p) =>
                p.id === activePageId
                    ? {
                        ...p,
                        widgets: p.widgets.map((w) =>
                            w.id === widgetId ? { ...w, hidden: !w.hidden } : w
                        ),
                    }
                    : p
            ),
        }));
    };

    const handleToggleLock = (widgetId: string) => {
        setState((prev) => ({
            ...prev,
            pages: prev.pages.map((p) =>
                p.id === activePageId
                    ? {
                        ...p,
                        widgets: p.widgets.map((w) =>
                            w.id === widgetId ? { ...w, locked: !w.locked } : w
                        ),
                    }
                    : p
            ),
        }));
    };

    const handleReorderWidget = (fromIndex: number, toIndex: number) => {
        setState((prev) => {
            const p = prev.pages.find((pg) => pg.id === activePageId);
            if (!p) return prev;
            const newWidgets = [...p.widgets];
            const [moved] = newWidgets.splice(fromIndex, 1);
            newWidgets.splice(toIndex, 0, moved);
            return {
                ...prev,
                pages: prev.pages.map((pg) =>
                    pg.id === activePageId ? { ...pg, widgets: newWidgets } : pg
                ),
            };
        });
    };

    // ── Bookmarks ──
    const handleApplyBookmark = async (bm: Bookmark) => {
        if (bm.page_id && state.pages.some((p) => p.id === bm.page_id)) {
            setActivePageId(bm.page_id);
        }
        if (bm.filters) {
            setState((prev) => ({ ...prev, globalFilters: bm.filters || [] }));
        }
        const cross = bm.cross_filters || {};
        setCrossFilters(cross);

        if (bm.visible_widget_ids) {
            setState((prev) => ({
                ...prev,
                pages: prev.pages.map((p) =>
                    p.id === (bm.page_id || activePageId)
                        ? {
                            ...p,
                            widgets: p.widgets.map((w) => ({
                                ...w,
                                hidden: !bm.visible_widget_ids!.includes(w.id),
                            })),
                        }
                        : p
                ),
            }));
        }

        await reQueryAllWidgets(bm.filters || [], cross);
        message.success(`View '${bm.name}' applied!`);
    };

    const handleSaveBookmark = (bm: Bookmark) => {
        setState((prev) => {
            const exists = prev.bookmarks.some((b) => b.id === bm.id);
            return {
                ...prev,
                bookmarks: exists
                    ? prev.bookmarks.map((b) => (b.id === bm.id ? bm : b))
                    : [...prev.bookmarks, bm],
            };
        });
        message.success(`Bookmark '${bm.name}' saved!`);
    };

    const handleDeleteBookmark = (id: string) => {
        setState((prev) => ({
            ...prev,
            bookmarks: prev.bookmarks.filter((b) => b.id !== id),
        }));
    };

    // ── DAX Measures ──
    const handleSaveMeasure = (meas: MeasureDefinition) => {
        setState((prev) => ({
            ...prev,
            measures: [...prev.measures.filter((m) => m.name !== meas.name), meas],
        }));
        message.success(`Measure '${meas.name}' ready for use in visual wells!`);
    };

    // ── Layout Change ──
    const handleLayoutChange = useCallback((layout: any[]) => {
        setState((prev) => ({
            ...prev,
            pages: prev.pages.map((p) =>
                p.id === activePageId
                    ? {
                        ...p,
                        widgets: p.widgets.map((w) => {
                            const l = layout.find((li) => li.i === w.id);
                            return l ? { ...w, layout: { x: l.x, y: l.y, w: l.w, h: l.h } } : w;
                        }),
                    }
                    : p
            ),
        }));
    }, [activePageId]);

    // ── Widget Duplication / Deletion ──
    const handleDuplicateWidget = (id: string) => {
        const w = currentWidgets.find((wi) => wi.id === id);
        if (!w) return;
        const dup: Widget = {
            ...w,
            id: crypto.randomUUID?.() || Math.random().toString(36).slice(2),
            layout: { ...w.layout, x: (w.layout.x + w.layout.w) % 12, y: w.layout.y },
            prompt_history: [...w.prompt_history],
        };
        setState((prev) => ({
            ...prev,
            pages: prev.pages.map((p) =>
                p.id === activePageId ? { ...p, widgets: [...p.widgets, dup] } : p
            ),
        }));
    };

    const handleDeleteWidget = (id: string) => {
        setState((prev) => ({
            ...prev,
            pages: prev.pages.map((p) =>
                p.id === activePageId ? { ...p, widgets: p.widgets.filter((w) => w.id !== id) } : p
            ),
        }));
        if (selectedWidgetId === id) setSelectedWidgetId(null);
        if (editingWidgetId === id) setEditingWidgetId(null);
    };

    const handleTitleChange = (id: string, title: string) => {
        setState((prev) => ({
            ...prev,
            pages: prev.pages.map((p) =>
                p.id === activePageId
                    ? {
                        ...p,
                        widgets: p.widgets.map((w) =>
                            w.id === id ? { ...w, config: { ...w.config, title } } : w
                        ),
                    }
                    : p
            ),
        }));
    };

    // ── Save Dashboard ──
    const handleSave = async () => {
        setSaving(true);
        try {
            await fetchAuth(`${API_BASE}/api/dashboards`, {
                method: 'POST',
                headers: { 'Content-Type': 'application/json' },
                body: JSON.stringify({
                    id: state.id,
                    title: state.title,
                    description: state.description,
                    file_id: fileId,
                    pages: state.pages.map((p) => ({
                        id: p.id,
                        title: p.title,
                        widgets: p.widgets.map((w) => ({
                            id: w.id,
                            config: w.config,
                            source_prompt: w.source_prompt,
                            prompt_history: w.prompt_history,
                            layout: w.layout,
                            hidden: w.hidden,
                            locked: w.locked,
                        })),
                    })),
                    global_filters: state.globalFilters,
                    measures: state.measures,
                    bookmarks: state.bookmarks,
                }),
            });
            message.success('Dashboard and pages saved!');
        } catch {
            message.error('Failed to save dashboard');
        } finally {
            setSaving(false);
        }
    };

    // ── Share ──
    const handleShare = () => {
        const url = `${window.location.href.split('?')[0]}?dashboard=${state.id}`;
        navigator.clipboard?.writeText(url);
        message.success('Share link copied to clipboard!');
    };

    // ── Export PNG ──
    const handleExportPng = async () => {
        if (!canvasRef.current) return;
        try {
            const html2canvas = (await import('html2canvas')).default;
            const canvas = await html2canvas(canvasRef.current, { scale: 2, backgroundColor: isDark ? '#0f172a' : '#ffffff' });
            const link = document.createElement('a');
            link.download = `${state.title || 'dashboard'}.png`;
            link.href = canvas.toDataURL();
            link.click();
            message.success('PNG exported!');
        } catch {
            message.error('Export failed');
        }
    };

    // ── Export PDF ──
    const handleExportPdf = async () => {
        if (!canvasRef.current) return;
        try {
            const html2canvas = (await import('html2canvas')).default;
            const { jsPDF } = await import('jspdf');
            const canvas = await html2canvas(canvasRef.current, { scale: 2, backgroundColor: isDark ? '#0f172a' : '#ffffff' });
            const imgData = canvas.toDataURL('image/png');
            const pdf = new jsPDF({ orientation: 'landscape', unit: 'px', format: [canvas.width, canvas.height] });
            pdf.addImage(imgData, 'PNG', 0, 0, canvas.width, canvas.height);
            pdf.save(`${state.title || 'dashboard'}.pdf`);
            message.success('PDF exported!');
        } catch {
            message.error('Export failed');
        }
    };

    // Present mode
    if (presenting) {
        return (
            <PresentMode
                widgets={currentWidgets}
                title={state.title}
                pageTitle={currentPage?.title}
                onExit={() => setPresenting(false)}
            />
        );
    }

    return (
        <div style={{
            minHeight: '100vh',
            background: isDark ? '#0f172a' : '#f8fafc',
            display: 'flex',
            flexDirection: 'column',
            paddingBottom: 130, // Space for fixed prompt bar & page tabs
        }}>
            <div style={{ padding: '6px 24px', display: 'flex', justifyContent: 'flex-end', background: isDark ? '#111827' : '#ffffff' }}>
                <Button size="small" onClick={handleLoadDashboard}>Load Dashboard</Button>
            </div>

            <DashboardHeader
                title={state.title}
                description={state.description}
                onTitleChange={(t) => setState((s) => ({ ...s, title: t }))}
                onSave={handleSave}
                onShare={handleShare}
                onPresent={() => setPresenting(true)}
                onExportPng={handleExportPng}
                onExportPdf={handleExportPdf}
                onAddWidget={() => message.info('Type a prompt in the bar below or pick a visual to add')}
                onOpenMeasures={() => setMeasureStudioOpen(true)}
                onOpenBookmarks={() => setBookmarksDrawerOpen(true)}
                onOpenSelection={() => setSelectionPaneOpen(true)}
                saving={saving}
            />

            <GlobalFilterBar
                filters={state.globalFilters}
                crossFilters={crossFilters}
                columns={columns}
                onFiltersChange={handleGlobalFiltersChange}
                onRemoveCrossFilter={handleRemoveCrossFilter}
                onClearAllCrossFilters={handleClearAllCrossFilters}
            />

            {/* Main Canvas Body with Optional Docked Panels */}
            <div style={{ display: 'flex', flex: 1, position: 'relative' }}>
                <div ref={canvasRef} style={{ flex: 1, padding: '16px 24px', minWidth: 0 }}>
                    {currentWidgets.length === 0 ? (
                        <div style={{
                            display: 'flex', flexDirection: 'column', alignItems: 'center',
                            justifyContent: 'center', height: 400, color: '#64748b',
                        }}>
                            {isAutoGenerating ? (
                                <>
                                    <div style={{ fontSize: 60, marginBottom: 16, animation: 'pulse 1.5s infinite' }}>🧠</div>
                                    <h3 style={{ color: '#94a3b8', marginBottom: 8 }}>Analyzing Business Context...</h3>
                                    <p>Automatically building your dashboard based on dataset patterns and domain intelligence.</p>
                                </>
                            ) : (
                                <>
                                    <div style={{ fontSize: 60, marginBottom: 16 }}>📊</div>
                                    <h3 style={{ color: '#94a3b8', marginBottom: 8 }}>No visuals on this page</h3>
                                    <p>Type an analytical prompt below to generate your first chart.</p>
                                    <p style={{ fontSize: 13, color: '#475569' }}>
                                        Try: "Monthly gross vs net revenue trend" or "Units sold by product category"
                                    </p>
                                </>
                            )}
                        </div>
                    ) : (
                        <DashboardCanvas
                            widgets={currentWidgets}
                            editingWidgetId={editingWidgetId}
                            selectedWidgetId={selectedWidgetId}
                            onLayoutChange={handleLayoutChange}
                            onEditWidget={(id) => {
                                setEditingWidgetId(id);
                                setSelectedWidgetId(id);
                            }}
                            onSelectWidget={(id) => setSelectedWidgetId(id)}
                            onDuplicateWidget={handleDuplicateWidget}
                            onDeleteWidget={handleDeleteWidget}
                            onFullscreenWidget={() => setPresenting(true)}
                            onTitleChange={handleTitleChange}
                            onFormatWidget={(id) => {
                                setSelectedWidgetId(id);
                                setActiveSidePanel('field_well');
                            }}
                            onDrillUp={handleDrillUp}
                            onDrillDown={handleDrillDown}
                            onExplainWidget={handleExplainWidget}
                            onCrossFilter={handleCrossFilter}
                        />
                    )}
                </div>

                {/* Docked Visual Field Well Panel */}
                {activeSidePanel === 'field_well' && selectedWidget && (
                    <FieldWellPanel
                        config={selectedWidget.config}
                        columns={columns}
                        measures={state.measures}
                        onChange={handleUpdateWidgetConfig}
                        onClose={() => setActiveSidePanel(null)}
                    />
                )}

                {/* Docked Format Panel */}
                {activeSidePanel === 'format' && selectedWidget && (
                    <FormatPanel
                        config={selectedWidget.config}
                        onChange={handleUpdateWidgetConfig}
                        onClose={() => setActiveSidePanel(null)}
                    />
                )}
            </div>

            {/* Bottom Floating Prompt Bar */}
            <PromptBar
                onSubmit={handlePromptSubmit}
                loading={promptLoading}
                history={promptHistory}
                suggestions={suggestions}
                onUndo={() => {}}
                canUndo={configSnapshots.length > 0}
                clarification={clarification}
                editingTitle={currentWidgets.find((w) => w.id === editingWidgetId)?.config.title}
                onCancelEdit={() => setEditingWidgetId(null)}
            />

            {/* Fixed Bottom Page Navigation Tabs */}
            <div style={{ position: 'fixed', bottom: 74, left: 0, right: 0, zIndex: 999 }}>
                <PageTabs
                    pages={state.pages}
                    activePageId={activePageId}
                    onSelectPage={(id) => {
                        setActivePageId(id);
                        setSelectedWidgetId(null);
                        setEditingWidgetId(null);
                    }}
                    onAddPage={handleAddPage}
                    onRenamePage={handleRenamePage}
                    onDeletePage={handleDeletePage}
                    onDuplicatePage={handleDuplicatePage}
                />
            </div>

            {/* DAX Measure Studio Modal */}
            <MeasureStudioModal
                open={measureStudioOpen}
                fileId={fileId}
                onClose={() => setMeasureStudioOpen(false)}
                onSave={handleSaveMeasure}
            />

            {/* Bookmarks Drawer */}
            <BookmarksDrawer
                open={bookmarksDrawerOpen}
                bookmarks={state.bookmarks}
                currentPageId={activePageId}
                currentFilters={state.globalFilters}
                currentCrossFilters={crossFilters}
                visibleWidgetIds={currentWidgets.filter((w) => !w.hidden).map((w) => w.id)}
                onClose={() => setBookmarksDrawerOpen(false)}
                onApplyBookmark={handleApplyBookmark}
                onSaveBookmark={handleSaveBookmark}
                onDeleteBookmark={handleDeleteBookmark}
            />

            {/* Selection & Layers Pane */}
            <SelectionPane
                open={selectionPaneOpen}
                widgets={currentWidgets}
                onClose={() => setSelectionPaneOpen(false)}
                onToggleVisibility={handleToggleVisibility}
                onToggleLock={handleToggleLock}
                onRenameWidget={handleTitleChange}
                onReorderWidget={handleReorderWidget}
                onSelectWidget={(id) => setSelectedWidgetId(id)}
            />

            {/* AI Explain Point Drawer */}
            <ExplainPointDrawer
                open={explainDrawerOpen}
                fileId={fileId}
                metric={explainContext.metric}
                dimension={explainContext.dimension}
                priorPoint={explainContext.priorPoint}
                currentPoint={explainContext.currentPoint}
                onClose={() => setExplainDrawerOpen(false)}
            />

            {/* Load Dashboard Modal */}
            <Modal
                title="Load Dashboard"
                open={loadModalOpen}
                onCancel={() => setLoadModalOpen(false)}
                footer={null}
            >
                <List
                    dataSource={dashboardList}
                    renderItem={(item) => (
                        <List.Item
                            actions={[<Button onClick={() => handleSelectDashboard(item.id)}>Load</Button>]}
                        >
                            <List.Item.Meta title={item.title} description={item.description || 'No description'} />
                        </List.Item>
                    )}
                />
            </Modal>
        </div>
    );
};

export default DashboardPage;
