/**
 * DashboardPage — Root orchestrator for the AI Dashboard Builder.
 *
 * Manages: widgets[], layout, activeWidgetId, promptHistory[], globalFilters,
 * present mode, save/share/export flows.
 */
import React, { useState, useCallback, useRef, useEffect } from 'react';
import { message, Modal, List, Button } from 'antd';
import type { Widget, ChartConfig, FilterCondition, InterpretResponse } from '../../types/dashboard';
import DashboardHeader from './DashboardHeader';
import GlobalFilterBar from './GlobalFilterBar';
import DashboardCanvas from './DashboardCanvas';
import PromptBar from './PromptBar';
import PresentMode from './PresentMode';
import { fetchAuth, API_BASE } from '../../api/client';
import { useTheme } from '../../hooks/useTheme';

interface PromptEntry {
    prompt: string;
    timestamp: number;
    chartTypeBefore?: string;
    chartTypeAfter?: string;
    widgetId?: string;
}

interface DashboardState {
    id: string;
    title: string;
    description: string;
    fileId: string;
    widgets: Widget[];
    globalFilters: FilterCondition[];
}

interface DashboardListItem {
    id: string;
    title: string;
    description?: string;
    widget_count?: number;
    updated_at?: number;
}

interface Props {
    fileId: string;
    columns?: string[];
}

const DashboardPage: React.FC<Props> = ({ fileId, columns = [] }) => {
    const { isDark } = useTheme();
    const [state, setState] = useState<DashboardState>({
        id: (crypto.randomUUID?.() || Math.random().toString(36).slice(2)),
        title: 'Untitled Dashboard',
        description: '',
        fileId,
        widgets: [],
        globalFilters: [],
    });

    const [promptLoading, setPromptLoading] = useState(false);
    const [promptHistory, setPromptHistory] = useState<PromptEntry[]>([]);
    const [suggestions, setSuggestions] = useState<string[]>([]);
    const [clarification, setClarification] = useState<string | undefined>();
    const [activeWidgetId, setActiveWidgetId] = useState<string | null>(null);
    const [presenting, setPresenting] = useState(false);
    const [saving, setSaving] = useState(false);
    const canvasRef = useRef<HTMLDivElement>(null);
    
    const [isAutoGenerating, setIsAutoGenerating] = useState(false);
    const autoGeneratedRef = useRef(false);

    // Track config history for undo
    const [configSnapshots, setConfigSnapshots] = useState<Widget[][]>([]);

    // BUG FIX: Properly typed (was any[])
    const [dashboardList, setDashboardList] = useState<DashboardListItem[]>([]);
    const [loadModalOpen, setLoadModalOpen] = useState(false);

    // Ref that always holds current widgets — used in stable callbacks to avoid stale closures
    // without adding state.widgets to dependency arrays (which recreates callbacks every render)
    const widgetsRef = useRef<Widget[]>(state.widgets);
    useEffect(() => { widgetsRef.current = state.widgets; }, [state.widgets]);

    const handleLoadDashboard = async () => {
        try {
            const resp = await fetchAuth(`${API_BASE}/api/dashboards`);
            if (resp.ok) {
                const data = await resp.json();
                setDashboardList(data.dashboards || []);
                setLoadModalOpen(true);
            }
        } catch {
            message.error('Failed to load dashboards');
        }
    };

    // BUG FIX: useCallback makes this reference stable so it can safely go in useEffect deps
    const handleSelectDashboard = useCallback(async (id: string) => {
        try {
            const resp = await fetchAuth(`${API_BASE}/api/dashboards/${id}`);
            if (resp.ok) {
                const data = await resp.json();
                setState(prev => ({
                    ...prev,
                    id: data.id,
                    title: data.title || 'Untitled Dashboard',
                    description: data.description || '',
                    widgets: data.widgets || [],
                    globalFilters: data.global_filters || [],
                }));
                setLoadModalOpen(false);
                message.success('Dashboard loaded!');
            }
        } catch {
            message.error('Failed to load dashboard');
        }
    }, []);

    // BUG FIX: handleSelectDashboard is now stable (useCallback) — safe in dep array
    useEffect(() => {
        const params = new URLSearchParams(window.location.search);
        const dashId = params.get('dashboard');
        if (dashId) handleSelectDashboard(dashId);
    }, [handleSelectDashboard]);

    // BUG FIX: Depend only on [fileId]. The autoGeneratedRef guard prevents double-firing.
    // Removing state.widgets.length prevents the loop: widgets cleared → length=0 → re-triggers.
    useEffect(() => {
        const params = new URLSearchParams(window.location.search);
        if (params.get('dashboard')) return; // Loaded existing — skip auto-gen

        if (!autoGeneratedRef.current && fileId) {
            autoGeneratedRef.current = true;
            setIsAutoGenerating(true);

            fetchAuth(`${API_BASE}/api/dashboard/auto`, {
                method: 'POST',
                headers: { 'Content-Type': 'application/json' },
                body: JSON.stringify({ file_id: fileId }),
            })
            .then(res => {
                if (!res.ok) throw new Error("Auto-gen failed");
                return res.json();
            })
            .then(data => {
                if (data.widgets && data.widgets.length > 0) {
                    const newWidgets: Widget[] = data.widgets.map((w: any, idx: number) => ({
                        id: crypto.randomUUID?.() || Math.random().toString(36).slice(2),
                        config: w.config,
                        data: w.data || [],
                        sql: w.sql,
                        source_prompt: "Auto-generated dashboard based on dataset context",
                        prompt_history: ["Auto-generated"],
                        error: w.error,
                        layout: {
                            x: (idx * 6) % 12,
                            y: Math.floor(idx / 2) * 4,
                            w: 6,
                            h: 4,
                        }
                    }));
                    setState(prev => ({ ...prev, widgets: newWidgets }));
                    message.success("Dashboard auto-generated based on business context!");
                }
            })
            .catch(err => {
                console.error("Auto generation failed", err);
            })
            .finally(() => {
                setIsAutoGenerating(false);
            });
        }
    }, [fileId]);  // ← only fileId; ref guard prevents double-firing

    // ── Prompt Submission ──
    const handlePromptSubmit = useCallback(async (prompt: string) => {
        setPromptLoading(true);
        setClarification(undefined);

        try {
            const activeWidget = activeWidgetId
                ? state.widgets.find(w => w.id === activeWidgetId)
                : undefined;

            const body: any = {
                message: prompt,
                file_id: fileId,
                conversation_history: promptHistory.map(h => h.prompt),
            };
            if (activeWidget) {
                body.current_config = activeWidget.config;
            }

            const resp = await fetchAuth(`${API_BASE}/api/dashboard/interpret`, {
                method: 'POST',
                headers: { 'Content-Type': 'application/json' },
                body: JSON.stringify(body),
            });
            if (!resp.ok) throw new Error('Interpretation failed');
            const result: InterpretResponse = await resp.json();

            if (result.clarification) {
                setClarification(result.clarification.clarification);
                setSuggestions(result.clarification.suggestions || []);
                return;
            }

            // Show error from the backend but still create the widget if config was returned
            if (!result.success && result.error && !result.config) {
                message.error(result.error);
                return;
            }

            if (result.config) {
                // Show a warning if SQL execution failed but config was interpreted
                if (!result.success && result.error) {
                    message.warning(`Chart created but query had issues: ${result.error}`);
                }

                // BUG FIX: Capture the new widget ID synchronously inside the setState updater
                // via a local variable (closure). This avoids the pendingActiveIdRef race
                // condition where the ref was set inside the updater (sync) but React could
                // batch the state update and the ref read happened before the widget rendered.
                let newWidgetId: string | null = null;

                setState(prev => {
                    // Save snapshot of current widgets before mutating
                    setConfigSnapshots(snaps => [...snaps, prev.widgets.map(w => ({ ...w }))]);

                    const activeWidgetExists = activeWidgetId && prev.widgets.some(w => w.id === activeWidgetId);

                    if (activeWidgetExists) {
                        // Update existing widget
                        return {
                            ...prev,
                            widgets: prev.widgets.map(w =>
                                w.id === activeWidgetId
                                    ? {
                                        ...w,
                                        config: result.config!,
                                        data: result.data || w.data,
                                        sql: result.sql || w.sql,
                                        source_prompt: prompt,
                                        prompt_history: [...w.prompt_history, prompt],
                                        error: (!result.success && result.error) ? result.error : undefined,
                                    }
                                    : w
                            ),
                        };
                    } else {
                        // Create new widget — capture ID synchronously before React flushes
                        const newId = crypto.randomUUID?.() || Math.random().toString(36).slice(2);
                        newWidgetId = newId;
                        const newWidget: Widget = {
                            id: newId,
                            config: result.config!,
                            source_prompt: prompt,
                            prompt_history: [prompt],
                            layout: {
                                x: (prev.widgets.length * 6) % 12,
                                y: Math.floor(prev.widgets.length / 2) * 4,
                                w: 6,
                                h: 4,
                            },
                            data: result.data || [],
                            sql: result.sql || undefined,
                            error: (!result.success && result.error) ? result.error : undefined,
                        };
                        return { ...prev, widgets: [...prev.widgets, newWidget] };
                    }
                });

                // newWidgetId is set synchronously in the updater above — no race condition
                if (newWidgetId) {
                    setActiveWidgetId(newWidgetId);
                }

                const finalActiveId = newWidgetId || activeWidgetId;
                setPromptHistory(prev => [...prev, {
                    prompt,
                    timestamp: Date.now(),
                    chartTypeBefore: activeWidget?.config.chart_type,
                    chartTypeAfter: result.config!.chart_type,
                    widgetId: finalActiveId || undefined,
                }]);

                // Fetch suggestions for the new config
                fetchSuggestions(result.config);
            }
        } catch (err: any) {
            message.error(err.message || 'Failed to interpret prompt');
        } finally {
            setPromptLoading(false);
        }
    }, [fileId, state.widgets, activeWidgetId, promptHistory]);

    // ── Fetch Follow-up Suggestions ──
    const fetchSuggestions = async (config: ChartConfig) => {
        try {
            const resp = await fetchAuth(`${API_BASE}/api/dashboard/suggest`, {
                method: 'POST',
                headers: { 'Content-Type': 'application/json' },
                body: JSON.stringify({ file_id: fileId, current_config: config }),
            });
            if (resp.ok) {
                const data = await resp.json();
                setSuggestions(data.suggestions || []);
            }
        } catch {
            setSuggestions([]);
        }
    };

    // ── Re-query a widget (e.g. when global filters change) ──
    const reQueryWidget = async (widget: Widget, filters: FilterCondition[]) => {
        try {
            const resp = await fetchAuth(`${API_BASE}/api/dashboard/query`, {
                method: 'POST',
                headers: { 'Content-Type': 'application/json' },
                body: JSON.stringify({ config: widget.config, file_id: fileId, global_filters: filters }),
            });
            if (resp.ok) {
                const data = await resp.json();
                return data.data || [];
            }
            return widget.data || [];
        } catch {
            return widget.data || [];
        }
    };

    // ── Undo ──
    const handleUndo = useCallback(async () => {
        if (configSnapshots.length === 0) return;
        const prevWidgets = configSnapshots[configSnapshots.length - 1];
        const requeried = await Promise.all(
            prevWidgets.map(async w => ({
                ...w,
                data: await reQueryWidget(w, state.globalFilters),
            }))
        );
        setState(s => ({ ...s, widgets: requeried }));
        setConfigSnapshots(ss => ss.slice(0, -1));
        setPromptHistory(ph => ph.slice(0, -1));
    }, [configSnapshots, state.globalFilters]);

    // ── Layout Change ──
    const handleLayoutChange = useCallback((layout: any[]) => {
        setState(prev => ({
            ...prev,
            widgets: prev.widgets.map(w => {
                const l = layout.find(li => li.i === w.id);
                return l ? { ...w, layout: { x: l.x, y: l.y, w: l.w, h: l.h } } : w;
            }),
        }));
    }, []);

    // ── Widget Actions ──
    const handleEditWidget = (id: string) => setActiveWidgetId(id);

    const handleDuplicateWidget = (id: string) => {
        const w = state.widgets.find(wi => wi.id === id);
        if (!w) return;
        const dup: Widget = {
            ...w,
            id: (crypto.randomUUID?.() || Math.random().toString(36).slice(2)),
            layout: { ...w.layout, x: (w.layout.x + w.layout.w) % 12, y: w.layout.y },
            prompt_history: [...w.prompt_history],
        };
        setState(prev => ({ ...prev, widgets: [...prev.widgets, dup] }));
    };

    const handleDeleteWidget = (id: string) => {
        setState(prev => ({ ...prev, widgets: prev.widgets.filter(w => w.id !== id) }));
        if (activeWidgetId === id) setActiveWidgetId(null);
    };

    const handleFullscreen = (id: string) => {
        const idx = state.widgets.findIndex(w => w.id === id);
        if (idx >= 0) setPresenting(true);
    };

    const handleTitleChange = (id: string, title: string) => {
        setState(prev => ({
            ...prev,
            widgets: prev.widgets.map(w =>
                w.id === id ? { ...w, config: { ...w.config, title } } : w
            ),
        }));
    };

    // ── Global Filters ──
    // BUG FIX: widgetsRef reads current widgets without needing state.widgets in deps.
    // This makes the callback stable (dep array []) so GlobalFilterBar never re-subscribes.
    // Also marks widgets as loading while re-querying for visual feedback.
    const handleGlobalFiltersChange = useCallback(async (filters: FilterCondition[]) => {
        const currentWidgets = widgetsRef.current;
        setState(prev => ({
            ...prev,
            globalFilters: filters,
            widgets: prev.widgets.map(w => ({ ...w, loading: true })),
        }));
        const updatedWidgets = await Promise.all(
            currentWidgets.map(async w => ({
                ...w,
                loading: false,
                data: await reQueryWidget(w, filters),
            }))
        );
        setState(prev => ({ ...prev, widgets: updatedWidgets }));
    }, []);  // stable: reads widgets via widgetsRef, not closure

    // ── Save ──
    const handleSave = async () => {
        setSaving(true);
        try {
            await fetchAuth(`${API_BASE}/api/dashboards`, {
                method: 'POST',
                headers: { 'Content-Type': 'application/json' },
                body: JSON.stringify({
                    id: state.id,
                    title: state.title,
                    description: state.description,
                    file_id: fileId,
                    widgets: state.widgets.map(w => ({
                        id: w.id,
                        config: w.config,
                        source_prompt: w.source_prompt,
                        prompt_history: w.prompt_history,
                        layout: w.layout,
                    })),
                    global_filters: state.globalFilters,
                }),
            });
            // BUG FIX: Only persist config metadata to localStorage — NOT the data rows.
            // Data rows can be hundreds of KB per widget and will exceed the 5 MB localStorage limit.
            localStorage.setItem(`dashboard_${state.id}`, JSON.stringify({
                id: state.id,
                title: state.title,
                description: state.description,
                fileId: state.fileId,
                globalFilters: state.globalFilters,
                widgets: state.widgets.map(w => ({
                    id: w.id,
                    config: w.config,
                    source_prompt: w.source_prompt,
                    prompt_history: w.prompt_history,
                    layout: w.layout,
                    // Intentionally omit: data, sql (too large for localStorage)
                })),
            }));
            message.success('Dashboard saved!');
        } catch (err: any) {
            message.error('Failed to save dashboard');
        } finally {
            setSaving(false);
        }
    };

    // ── Share ──
    const handleShare = () => {
        const url = `${window.location.href.split('?')[0]}?dashboard=${state.id}`;
        navigator.clipboard?.writeText(url);
        message.success('Share link copied to clipboard!');
    };

    // ── Export PNG ──
    const handleExportPng = async () => {
        if (!canvasRef.current) return;
        try {
            const html2canvas = (await import('html2canvas')).default;
            const canvas = await html2canvas(canvasRef.current, { scale: 2, backgroundColor: isDark ? '#0f172a' : '#ffffff' });
            const link = document.createElement('a');
            link.download = `${state.title || 'dashboard'}.png`;
            link.href = canvas.toDataURL();
            link.click();
            message.success('PNG exported!');
        } catch {
            message.error('Export failed');
        }
    };

    // ── Export PDF ──
    const handleExportPdf = async () => {
        if (!canvasRef.current) return;
        try {
            const html2canvas = (await import('html2canvas')).default;
            const { jsPDF } = await import('jspdf');
            const canvas = await html2canvas(canvasRef.current, { scale: 2, backgroundColor: isDark ? '#0f172a' : '#ffffff' });
            const imgData = canvas.toDataURL('image/png');
            const pdf = new jsPDF({ orientation: 'landscape', unit: 'px', format: [canvas.width, canvas.height] });
            pdf.addImage(imgData, 'PNG', 0, 0, canvas.width, canvas.height);
            pdf.save(`${state.title || 'dashboard'}.pdf`);
            message.success('PDF exported!');
        } catch {
            message.error('Export failed');
        }
    };

    // ── Add Widget (empty) ──
    const handleAddWidget = () => {
        setActiveWidgetId(null);
        message.info('Type a prompt below to create a new chart');
    };

    // Present mode
    if (presenting) {
        return (
            <PresentMode
                widgets={state.widgets}
                title={state.title}
                onExit={() => setPresenting(false)}
            />
        );
    }

    return (
        <div style={{
            minHeight: '100vh', background: isDark ? '#0f172a' : '#f8fafc',
            display: 'flex', flexDirection: 'column',
            paddingBottom: 120, /* space for prompt bar */
        }}>
            <div style={{ padding: '8px 24px', display: 'flex', justifyContent: 'flex-end', background: isDark ? '#1e293b' : '#ffffff' }}>
                <Button size="small" onClick={handleLoadDashboard}>Load Dashboard</Button>
            </div>
            <DashboardHeader
                title={state.title}
                description={state.description}
                onTitleChange={t => setState(s => ({ ...s, title: t }))}
                onSave={handleSave}
                onShare={handleShare}
                onPresent={() => setPresenting(true)}
                onExportPng={handleExportPng}
                onExportPdf={handleExportPdf}
                onAddWidget={handleAddWidget}
                saving={saving}
            />

            <GlobalFilterBar
                filters={state.globalFilters}
                columns={columns}
                onFiltersChange={handleGlobalFiltersChange}
            />

            <div ref={canvasRef} style={{ flex: 1, padding: '16px 24px' }}>
                {state.widgets.length === 0 ? (
                    <div style={{
                        display: 'flex', flexDirection: 'column', alignItems: 'center',
                        justifyContent: 'center', height: 400, color: '#64748b',
                    }}>
                        {isAutoGenerating ? (
                            <>
                                <div style={{ fontSize: 60, marginBottom: 16, animation: 'pulse 1.5s infinite' }}>🧠</div>
                                <h3 style={{ color: '#94a3b8', marginBottom: 8 }}>Analyzing Business Context...</h3>
                                <p>Automatically building your dashboard based on dataset patterns and domain intelligence.</p>
                            </>
                        ) : (
                            <>
                                <div style={{ fontSize: 60, marginBottom: 16 }}>📊</div>
                                <h3 style={{ color: '#94a3b8', marginBottom: 8 }}>No charts yet</h3>
                                <p>Type a prompt below to create your first visualization</p>
                                <p style={{ fontSize: 13, color: '#475569' }}>
                                    Try: "Show monthly revenue as a bar chart" or "What's the split of customers by tier?"
                                </p>
                            </>
                        )}
                    </div>
                ) : (
                    <DashboardCanvas
                        widgets={state.widgets}
                        onLayoutChange={handleLayoutChange}
                        onEditWidget={handleEditWidget}
                        onDuplicateWidget={handleDuplicateWidget}
                        onDeleteWidget={handleDeleteWidget}
                        onFullscreenWidget={handleFullscreen}
                        onTitleChange={handleTitleChange}
                    />
                )}
            </div>

            <PromptBar
                onSubmit={handlePromptSubmit}
                loading={promptLoading}
                history={promptHistory}
                suggestions={suggestions}
                onUndo={handleUndo}
                canUndo={configSnapshots.length > 0}
                clarification={clarification}
            />

            <Modal
                title="Load Dashboard"
                open={loadModalOpen}
                onCancel={() => setLoadModalOpen(false)}
                footer={null}
            >
                <List
                    dataSource={dashboardList}
                    renderItem={item => (
                        <List.Item
                            actions={[<Button onClick={() => handleSelectDashboard(item.id)}>Load</Button>]}
                        >
                            <List.Item.Meta title={item.title} description={item.description || 'No description'} />
                        </List.Item>
                    )}
                />
            </Modal>
        </div>
    );
};

export default DashboardPage;
